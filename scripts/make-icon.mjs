// Draws the Sieve mark (src/components/sieve/shell/sieve-mark.json, the same
// geometry the top-bar logo renders) as the app's icon files:
//   src-tauri/icons/source.svg      the icon source, mint on transparent
//   src/app/icon.svg                the favicon (Next's icon file convention)
//   src-tauri/icons/source-1024.png rasterised with @resvg/resvg-js
//   src-tauri/icons/*               `tauri icon` from that PNG (app, installer and tray icon)
//   test-results/screens/icon-<n>.png  previews at 16, 32 and 256 px
// The colour is the dark theme's --primary, read from src/styles/tokens.css.
// Usage: node scripts/make-icon.mjs   (add --no-tauri to skip `tauri icon`)
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Resvg } from "@resvg/resvg-js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const at = (p) => join(ROOT, p);

const mark = JSON.parse(readFileSync(at("src/components/sieve/shell/sieve-mark.json"), "utf8"));
const tokens = readFileSync(at("src/styles/tokens.css"), "utf8");
const color = tokens.match(/--primary:\s*(#[0-9a-fA-F]{6})/)?.[1];
if (!color) throw new Error("make-icon: no --primary colour in tokens.css");

const { ring, lines } = mark;
const segments = lines.segments
  .map(([x1, y1, x2, y2]) => `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"/>`)
  .join("");
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${mark.size} ${mark.size}" width="${mark.size}" height="${mark.size}">
  <!-- Sieve mark: a ring with parallel diagonal lines clipped inside it. Own artwork. Generated by scripts/make-icon.mjs from src/components/sieve/shell/sieve-mark.json; edit those, not this file. -->
  <defs><clipPath id="mesh"><circle cx="${ring.cx}" cy="${ring.cy}" r="${ring.r}"/></clipPath></defs>
  <g clip-path="url(#mesh)" stroke="${color}" stroke-width="${lines.width}">${segments}</g>
  <circle cx="${ring.cx}" cy="${ring.cy}" r="${ring.r}" fill="none" stroke="${color}" stroke-width="${ring.width}"/>
</svg>
`;

writeFileSync(at("src-tauri/icons/source.svg"), svg);
writeFileSync(at("src/app/icon.svg"), svg);

const png = (width) => new Resvg(svg, { fitTo: { mode: "width", value: width }, background: "rgba(0,0,0,0)" }).render().asPng();
writeFileSync(at("src-tauri/icons/source-1024.png"), png(1024));

mkdirSync(at("test-results/screens"), { recursive: true });
for (const n of [16, 32, 256]) writeFileSync(at(`test-results/screens/icon-${n}.png`), png(n));

if (!process.argv.includes("--no-tauri")) {
  // `tauri icon` writes every size Tauri bundles (ico, icns, PNGs) next to the source.
  execFileSync(process.platform === "win32" ? "pnpm.cmd" : "pnpm", ["tauri", "icon", "src-tauri/icons/source-1024.png"], {
    cwd: ROOT,
    stdio: "inherit",
    shell: process.platform === "win32",
  });
  // Sieve is a Windows desktop app: the mobile sets `tauri icon` also writes are not kept.
  for (const d of ["android", "ios"]) rmSync(at(`src-tauri/icons/${d}`), { recursive: true, force: true });
}
console.log(`make-icon: wrote the mark in ${color}`);
