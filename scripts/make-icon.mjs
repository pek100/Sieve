// Derives the Sieve mark's geometry (writing src/components/sieve/shell/sieve-mark.json,
// which the top-bar logo renders) and draws it as the app's icon files:
//   src-tauri/icons/source.svg      the icon source, mint on transparent
//   src/app/icon.svg                the favicon (Next's icon file convention)
//   src-tauri/icons/source-1024.png rasterised with @resvg/resvg-js
//   src-tauri/icons/*               `tauri icon` from that PNG (app, installer and tray icon)
//   test-results/screens/icon-<n>.png  previews at 16, 32 and 256 px
// The colour is the dark theme's --primary, read from src/styles/tokens.css.
// Usage: node scripts/make-icon.mjs   (add --no-tauri to skip `tauri icon`)
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Resvg } from "@resvg/resvg-js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const at = (p) => join(ROOT, p);

const tokens = readFileSync(at("src/styles/tokens.css"), "utf8");
const color = tokens.match(/--primary:\s*(#[0-9a-fA-F]{6})/)?.[1];
if (!color) throw new Error("make-icon: no --primary colour in tokens.css");

// The design: a sieve seen from the side. A rounded rim above a bowl (the lower half of a
// circle) cut by diagonal slots. The slots are fitted to the bowl, never laid on a fixed grid:
// measure the bowl along the slot normal (s = x + y), centre the first and last mint stripes
// on its two extremes so they merge with the bowl's edge, and space the rest evenly. A fixed
// grid shaved the curve wherever a slot happened to land on it.
const DESIGN = {
  size: 64,
  rim: { x: 3, y: 15, width: 58, height: 5.5 },
  bowl: { cx: 32, cy: 23.5, r: 26 }, // the flat top of the bowl is y = cy
  stripes: 6, // mint stripes across the bowl; slots = stripes - 1
  stripeWidth: 4.2, // perpendicular width of each mint stripe
};

const round = (n) => Math.round(n * 100) / 100;

/** Extremes of s = x + y over the bowl (its chord and its lower arc). */
function bowlExtent({ cx, cy, r }) {
  const s = [cx - r + cy, cx + r + cy];
  for (let i = 0; i <= 720; i++) {
    const t = (Math.PI * i) / 720;
    s.push(cx + r * Math.cos(t) + cy + r * Math.sin(t));
  }
  return [Math.min(...s), Math.max(...s)];
}

/** The slots: lines x + y = c, one between each pair of fitted stripes, and their width. */
function fitSlots(d) {
  const [lo, hi] = bowlExtent(d.bowl);
  const step = (hi - lo) / (d.stripes - 1); // stripe centre to centre, in s units
  const width = round(step / Math.SQRT2 - d.stripeWidth); // perpendicular slot width
  if (width <= 0) throw new Error("make-icon: stripes too wide for their count");
  const pad = 8; // run each slot past the bowl so its ends never show
  const lines = [];
  for (let i = 0; i < d.stripes - 1; i++) {
    const c = lo + step * (i + 0.5);
    // Both ends lie on x + y = c.
    lines.push([round(c - d.size - pad), d.size + pad, round(c + pad), -pad]);
  }
  return { width, lines };
}

const mark = { size: DESIGN.size, rim: DESIGN.rim, bowl: DESIGN.bowl, slots: fitSlots(DESIGN) };
writeFileSync(
  at("src/components/sieve/shell/sieve-mark.json"),
  `${JSON.stringify(mark, null, 2)}\n`,
);

const { rim, bowl, slots } = mark;
const slotLines = slots.lines.map(([x1, y1, x2, y2]) => `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"/>`).join("");
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${mark.size} ${mark.size}" width="${mark.size}" height="${mark.size}">
  <!-- Sieve mark: a sieve seen from the side, a rim above a bowl cut by fitted diagonal slots. Own artwork. Generated by scripts/make-icon.mjs (it also writes src/components/sieve/shell/sieve-mark.json); edit the script, not this file. -->
  <defs><mask id="bowl" maskUnits="userSpaceOnUse" x="-8" y="-8" width="80" height="80"><circle cx="${bowl.cx}" cy="${bowl.cy}" r="${bowl.r}" fill="#fff"/><path d="M-8 -8H72V${bowl.cy}H-8Z" fill="#000"/><g stroke="#000" stroke-width="${slots.width}">${slotLines}</g></mask></defs>
  <rect x="${rim.x}" y="${rim.y}" width="${rim.width}" height="${rim.height}" rx="${rim.height / 2}" fill="${color}"/>
  <path d="M0 0H${mark.size}V${mark.size}H0Z" fill="${color}" mask="url(#bowl)"/>
</svg>
`;

writeFileSync(at("src-tauri/icons/source.svg"), svg);
writeFileSync(at("src/app/icon.svg"), svg);

const png = (width) => new Resvg(svg, { fitTo: { mode: "width", value: width }, background: "rgba(0,0,0,0)" }).render().asPng();
writeFileSync(at("src-tauri/icons/source-1024.png"), png(1024));

mkdirSync(at("test-results/screens"), { recursive: true });
for (const n of [16, 32, 256]) writeFileSync(at(`test-results/screens/icon-${n}.png`), png(n));

if (!process.argv.includes("--no-tauri")) {
  // `tauri icon` writes every size Tauri bundles (ico, icns, PNGs) next to the source.
  execFileSync(process.platform === "win32" ? "pnpm.cmd" : "pnpm", ["tauri", "icon", "src-tauri/icons/source-1024.png"], {
    cwd: ROOT,
    stdio: "inherit",
    shell: process.platform === "win32",
  });
  // Sieve is a Windows desktop app: the mobile sets `tauri icon` also writes are not kept.
  for (const d of ["android", "ios"]) rmSync(at(`src-tauri/icons/${d}`), { recursive: true, force: true });
}
console.log(`make-icon: wrote the mark in ${color}`);
